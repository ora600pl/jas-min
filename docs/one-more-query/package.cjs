'use strict';
// Build/test first, then publish only an explicit allowlist of static files.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),{execFileSync}=require('node:child_process');
const base=__dirname,dist=path.join(base,'dist');
execFileSync(process.execPath,[path.join(base,'build.cjs')],{stdio:'inherit'});
execFileSync(process.execPath,[path.join(base,'test.cjs')],{stdio:'inherit'});
fs.mkdirSync(dist,{recursive:true});
const staging=fs.mkdtempSync(path.join(dist,'.package-'));
const upload=path.join(staging,'jas-min');fs.mkdirSync(upload);
for(const name of ['index.html','.htaccess','.nojekyll'])fs.copyFileSync(path.join(base,name==='index.html'?name:'deploy/'+name),path.join(upload,name));
fs.copyFileSync(path.join(base,'deploy/UPLOAD.md'),path.join(staging,'UPLOAD.md'));
const archive=path.join(staging,'jas-min-upload.zip');
execFileSync('zip',['-X','-q',archive,'jas-min/index.html','jas-min/.htaccess','jas-min/.nojekyll','UPLOAD.md'],{cwd:staging});
execFileSync('unzip',['-t',archive],{stdio:'inherit'});
const members=execFileSync('unzip',['-Z','-1',archive],{encoding:'utf8'}).trim().split('\n');
if(JSON.stringify(members)!==JSON.stringify(['jas-min/index.html','jas-min/.htaccess','jas-min/.nojekyll','UPLOAD.md']))throw Error('Unexpected archive contents');
const built=fs.readFileSync(path.join(base,'index.html'));
if(!execFileSync('unzip',['-p',archive,'jas-min/index.html']).equals(built))throw Error('Packaged HTML differs from tested build');
const site=path.join(dist,'site');fs.mkdirSync(site,{recursive:true});
const allowed=['index.html','.nojekyll'];
if(fs.readdirSync(site).some(n=>!allowed.includes(n)))throw Error('Unexpected files in Pages output; refusing to publish them');
for(const name of allowed)fs.copyFileSync(path.join(upload,name),path.join(site,name));
const zipPath=path.join(dist,'jas-min-upload.zip');fs.renameSync(archive,zipPath);
const checksum=b=>crypto.createHash('sha256').update(b).digest('hex');
const manifest={html:{bytes:built.length,sha256:checksum(built)},archive:{bytes:fs.statSync(zipPath).size,sha256:checksum(fs.readFileSync(zipPath)),files:members},pagesFiles:allowed};
fs.writeFileSync(path.join(dist,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
// Clean only the exact, known files generated by this invocation; never recurse.
for(const name of ['index.html','.htaccess','.nojekyll'])fs.unlinkSync(path.join(upload,name));
fs.rmdirSync(upload);fs.unlinkSync(path.join(staging,'UPLOAD.md'));fs.rmdirSync(staging);
console.log(JSON.stringify({archive:zipPath,pages:site,...manifest},null,2));
